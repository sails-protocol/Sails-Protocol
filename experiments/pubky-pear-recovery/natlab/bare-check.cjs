const DHT = require('hyperdht')
const createTestnet = require('hyperdht/testnet')
const b4a = require('b4a')
;(async () => {
  const t = await createTestnet(3)
  const a = new DHT({ bootstrap: t.bootstrap })
  const b = new DHT({ bootstrap: t.bootstrap })
  const kp = DHT.keyPair(b4a.alloc(32, 9))
  const srv = a.createServer((s) => { s.on('data', (d) => s.write(b4a.concat([b4a.from('pong:'), d]))); s.on('error', () => {}) })
  await srv.listen(kp)
  const s = b.connect(kp.publicKey)
  s.on('open', () => s.write(b4a.from('ping')))
  s.on('data', async (d) => { console.log('BARE OK', b4a.toString(d), 'runtime', typeof Bare !== 'undefined' ? 'bare' : 'node'); await b.destroy(); await a.destroy(); await t.destroy(); Bare.exit(0) })
  s.on('error', (e) => { console.log('ERR', e.message); Bare.exit(1) })
  setTimeout(() => { console.log('TIMEOUT'); Bare.exit(2) }, 20000)
})()
